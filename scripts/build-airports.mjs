#!/usr/bin/env node
// Rebuilds airports.js from the OpenFlights airport database (ODbL).
// Usage: node scripts/build-airports.mjs  (writes ./airports.js)
import { writeFileSync } from 'node:fs';
const SRC = 'https://raw.githubusercontent.com/jpatokal/openflights/master/data/airports.dat';
const text = await (await fetch(SRC)).text();
const rows = [];
for (const line of text.split('\n')) {
  if (!line.trim()) continue;
  const cols = []; let cur = '', q = false;
  for (const ch of line) { if (ch === '"') q = !q; else if (ch === ',' && !q) { cols.push(cur); cur = ''; } else cur += ch; }
  cols.push(cur);
  const [, name, city, country, iata, , lat, lon, , , , tz, type] = cols;
  if (type !== 'airport' || !iata || iata === '\\N' || iata.length !== 3 || !tz || tz === '\\N') continue;
  rows.push([iata, city, country, +(+lat).toFixed(2), +(+lon).toFixed(2), tz, name]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
const out = `// Generated by scripts/build-airports.mjs from OpenFlights airports.dat (ODbL).\n// Columns: [iata, city, country, lat, lon, tz, name]\n(function(root){var A=${JSON.stringify(rows)};if(typeof module!=="undefined"&&module.exports){module.exports=A;}else{root.AIRPORTS=A;}})(typeof globalThis!=="undefined"?globalThis:this);\n`;
writeFileSync(new URL('../airports.js', import.meta.url), out);
console.log(`wrote airports.js with ${rows.length} airports`);
